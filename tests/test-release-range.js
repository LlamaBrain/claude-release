import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { computeBump } from '../src/compute-bump.js';
const previous = process.cwd();
const cwd = mkdtempSync(join(tmpdir(), 'claude-release-range-'));
function git(...args) { return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore','pipe','pipe'] }).trim(); }
function commit(msg) { writeFileSync(join(cwd, 'file'), msg); git('add', 'file'); git('commit', '-qm', msg); return git('rev-parse', 'HEAD'); }
try {
  git('init', '-q'); git('config', 'user.email', 'fixture@example.invalid'); git('config', 'user.name', 'Fixture');
  writeFileSync(join(cwd, 'VERSION'), '1.0.0\n');
  writeFileSync(join(cwd, 'package.json'), JSON.stringify({version:'1.0.0'}));
  git('add', 'VERSION', 'package.json');
  const base = commit('chore: initialize'); git('tag', 'v1.0.0');
  const docs = commit('docs: explain usage');
  const fix = commit('fix: repair behavior');
  const feat = commit('feat: add behavior');
  commit('chore: subsequent work');
  process.chdir(cwd);
  const none = computeBump({ baseline: 'v1.0.0', target: docs });
  assert.equal(none.bump_kind, 'none'); assert.equal(none.next_version, 'v1.0.0');
  assert.equal(none.baseline_revision, base); assert.equal(none.target_revision, docs);
  const initial = computeBump({baselineRef:base, baselineVersion:'v1.0.0', baselineSurface:'VERSION', target:fix});
  const jsonInitial = computeBump({baselineRef:base, baselineVersion:'v1.0.0', baselineSurface:'package.json', baselinePointer:'/version', target:fix});
  assert.equal(jsonInitial.bump_kind, 'patch');
  assert.equal(initial.baseline_kind, 'declared_initial'); assert.equal(initial.bump_kind, 'patch');
  assert.throws(() => computeBump({baselineRef:base, baselineVersion:'v9.0.0', baselineSurface:'VERSION', target:fix}));
  const patch = computeBump({ baseline: 'v1.0.0', target: fix });
  assert.equal(computeBump({baseline:'v1.0.0',target:fix,typeMap:{fix:'none'}}).bump_kind, 'none');
  assert.equal(patch.bump_kind, 'patch'); assert.equal(patch.next_version, 'v1.0.1');
  const minor = computeBump({ baseline: 'v1.0.0', target: feat });
  assert.equal(minor.bump_kind, 'minor'); assert.equal(minor.next_version, 'v1.1.0');
  assert.equal(minor.commits.length, 3);
  assert.throws(() => computeBump({ baseline: 'missing-ref', target: feat }));
  assert.throws(() => computeBump({ baseline: 'v1.0.0', target: base + 'invalid' }));
  const payload = Buffer.from(JSON.stringify({schema_version: 1, commits: [{oid: 'a'.repeat(40), message: 'feat(ui): add menu'}, {oid: 'b'.repeat(40), message: 'fix!: remove API\n\nBREAKING CHANGE: Use the replacement.'}]})).toString('base64url');
  const squash = commit('chore: integrate work\n\nCaptain-Changes: ' + payload);
  const merged = computeBump({ baseline: 'v1.0.0', target: squash });
  assert.equal(merged.bump_kind, 'major');
  assert.equal(computeBump({ baseline: 'v1.0.0', target: squash, bumpOverride: 'patch' }).bump_kind, 'major');
  assert.equal(merged.commits.filter(c => c.squash_hash === squash).length, 2);
  git('checkout', '-qb', 'custom', 'v1.0.0');
  const custom = commit('update: revise metadata');
  assert.throws(() => computeBump({baseline:'v1.0.0',target:custom}));
  assert.equal(computeBump({baseline:'v1.0.0',target:custom,typeMap:{update:'none'}}).bump_kind, 'none');
  const customBreaking = commit('update!: remove interface\n\nBREAKING CHANGE: Use the replacement.');
  assert.equal(computeBump({baseline:'v1.0.0',target:customBreaking,typeMap:{update:'none'},bumpOverride:'patch'}).bump_kind, 'major');
  git('tag','v1.1.0',feat);
  git('checkout','-qb','second-release',feat);
  const secondFix = commit('fix: repair next release');
  git('tag','v9.0.0-rc.1',secondFix);
  const selected = computeBump({baseline:'latest-stable',target:secondFix});
  assert.equal(selected.previous_version,'v1.1.0'); assert.equal(selected.baseline_revision,feat); assert.equal(selected.next_version,'v1.1.1');
  git('tag','v1.1.1',secondFix);
  const repeat = computeBump({baseline:'latest-stable',target:secondFix});
  assert.equal(repeat.bump_kind,'none'); assert.equal(repeat.previous_version,'v1.1.1');
  git('checkout','-qb','unrelated',base); const other=commit('fix: unrelated'); git('tag','v99.0.0',other);
  assert.equal(computeBump({baseline:'latest-stable',target:secondFix}).previous_version,'v1.1.1');
  git('tag','1.1.1',secondFix);
  assert.throws(()=>computeBump({baseline:'latest-stable',target:secondFix}),/ambiguous/);
  console.log('explicit release range and aggregation passed');
} finally { process.chdir(previous); rmSync(cwd, { recursive: true, force: true }); }
